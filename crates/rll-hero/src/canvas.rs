const _: () = assert!(GLYPHS.len() == FONT.len());

pub struct Canvas {
    px: Vec<u8>,
}

impl Canvas {
    pub fn new() -> Self {
        Canvas {
            px: vec![BG; W * H],
        }
    }

    /// Fill a rectangle; whatever falls outside the canvas is cut off.
    pub fn rect(&mut self, x: usize, y: usize, w: usize, h: usize, c: u8) {
        for yy in y..(y + h).min(H) {
            for xx in x..(x + w).min(W) {
                self.px[yy * W + xx] = c;
            }
        }
    }

    /// Width in pixels of `s` at `scale`.
    pub fn text_width(s: &str, scale: usize) -> usize {
        s.chars().count() * 6 * scale
    }

    /// Draw `s` (upper-cased; unknown characters are blanks) with its top-left at (x, y).
    pub fn text(&mut self, x: usize, y: usize, s: &str, scale: usize, c: u8) {
        for (n, ch) in s.to_ascii_uppercase().chars().enumerate() {
            let glyph = FONT[GLYPHS.find(ch).unwrap_or(0)];
            for (row, bits) in glyph.iter().enumerate() {
                for col in 0..5 {
                    if bits >> (4 - col) & 1 == 1 {
                        self.rect(x + (n * 6 + col) * scale, y + row * scale, scale, scale, c);
                    }
                }
            }
        }
    }

    pub fn to_png(&self) -> Vec<u8> {
        png::encode(W, H, &PALETTE, &self.px)
    }
}

impl Default for Canvas {
    fn default() -> Self {
        Self::new()
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn rect_is_clipped_and_text_marks_pixels() {
        let mut c = Canvas::new();
        c.rect(W - 2, H - 2, 10, 10, RED);
        assert_eq!(c.px[H * W - 1], RED);
        c.text(10, 10, "a?", 2, TEXT);
        assert!(c.px.contains(&TEXT));
        assert_eq!(Canvas::text_width("ab", 2), 24);
        assert_eq!(Canvas::default().px, Canvas::new().px);
    }
}
